/** Presents a stored finding with its catalogue text. */
export function presentFinding(f, ctx) {
  const def = CHECKS[f.check_id] || {};
  const c = { ...ctx, f };
  const call = fn => { try { return typeof fn === "function" ? fn(c) : fn ?? null; } catch { return null; } };
  return {
    ...f,
    category_label: CATEGORIES[f.category]?.label || f.category,
    why: def.why || null,
    impact: def.impact || null,
    steps: call(def.steps) || [],
    code: call(def.code),
    time: def.time || null,
    expertise: def.expertise || null,
    verify: call(def.verify),
    refs: def.refs || [],
    opportunity: !!def.opportunity,
  };
}
